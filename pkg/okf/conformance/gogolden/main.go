// Command gogolden derives the cross-language conformance golden (issue #171)
// from binder's Go source of truth.
//
// It reads the shared INPUT corpus (scripts/conformance/corpus.json) and, for
// each case, runs the REAL Go implementation and records what it actually
// produces:
//
//   - frontmatter cases run through native.Codec.ParseConcept, so the recorded
//     error text is the exact string fmt.Errorf emits in
//     pkg/okf/native/native.go — not a copy of it;
//   - actor cases run through okfrules.IsHumanActor / okf.IsValidActor, so the
//     recorded booleans are whatever the real predicates in
//     internal/okfrules/trust.go and pkg/okf/trust.go return.
//
// The output JSON is the golden the other implementations (astro-okf TS, the
// validate-plugin.sh Python copy, the two testdata prose fixtures) are diffed
// against. Because it is generated by executing the real code, editing a Go
// error string or actor rule changes this golden automatically, which is what
// makes the conformance suite fail once per copy that did not follow. If this
// program ever hard-coded the strings, it would be a fourth copy rather than a
// derivation — so it must only ever OBSERVE the Go functions, never restate
// their literals.
//
// Scope: this golden covers the two STRUCTURAL frontmatter error strings, the
// wrapped-YAML error prefix (`invalid frontmatter: `), the two actor predicates
// (`IsHumanActor`, `IsValidActor`), `okf.TrustTier`, and `okfrules.IsStale`
// (issues #171 and #175).
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/ghchinoy/binder/internal/okfrules"
	"github.com/ghchinoy/binder/pkg/okf"
	"github.com/ghchinoy/binder/pkg/okf/native"
)

type corpus struct {
	Frontmatter []struct {
		Name       string `json:"name"`
		Input      string `json:"input"`
		PrefixOnly bool   `json:"prefixOnly,omitempty"`
	} `json:"frontmatter"`
	Actors []string `json:"actors"`
	Tiers  []struct {
		Name     string `json:"name"`
		Verified []struct {
			By string `json:"by"`
			At string `json:"at,omitempty"`
		} `json:"verified"`
	} `json:"tiers"`
	Staleness []struct {
		Name       string `json:"name"`
		StaleAfter string `json:"staleAfter"`
		Today      string `json:"today"`
	} `json:"staleness"`
}

type golden struct {
	Canonical   canonical           `json:"canonical"`
	Frontmatter []frontmatterResult `json:"frontmatter"`
	Actors      []actorResult       `json:"actors"`
	Tiers       []tierResult        `json:"tiers"`
	Staleness   []stalenessResult   `json:"staleness"`
}

type canonical struct {
	UnterminatedError string `json:"unterminatedError"`
	NonmappingError   string `json:"nonmappingError"`
	WrappedPrefix     string `json:"wrappedPrefix"`
}

type frontmatterResult struct {
	Name       string `json:"name"`
	Error      string `json:"error"`
	PrefixOnly bool   `json:"prefixOnly,omitempty"`
}

type actorResult struct {
	Actor   string `json:"actor"`
	IsHuman bool   `json:"isHuman"`
	IsValid bool   `json:"isValid"`
}

type tierResult struct {
	Name string `json:"name"`
	Tier string `json:"tier"`
}

type stalenessResult struct {
	Name    string `json:"name"`
	IsStale bool   `json:"isStale"`
}

// observeErr runs the real codec over input and returns Go's actual error text
// (or "" if it did not error). It never restates a literal — the returned string
// is whatever native.go emitted.
func observeErr(codec *native.Codec, input string) string {
	if _, err := codec.ParseConcept("conformance.md", []byte(input)); err != nil {
		return err.Error()
	}
	return ""
}

func main() {
	path := os.Getenv("OKF_CONFORMANCE_CORPUS")
	if len(os.Args) > 1 {
		path = os.Args[1]
	}
	if path == "" {
		fmt.Fprintln(os.Stderr, "usage: gogolden <corpus.json>  (or set OKF_CONFORMANCE_CORPUS)")
		os.Exit(2)
	}

	raw, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gogolden: reading corpus: %v\n", err)
		os.Exit(2)
	}
	var c corpus
	if err := json.Unmarshal(raw, &c); err != nil {
		fmt.Fprintf(os.Stderr, "gogolden: parsing corpus: %v\n", err)
		os.Exit(2)
	}

	codec := native.New()
	var g golden

	// Observe the two structural errors Go produces from minimal triggering
	// inputs. These inputs live here (not in the corpus) so the canonical record
	// is independent of whatever the shared corpus happens to contain — that
	// independence is exactly what lets the coverage check assert the corpus
	// still reproduces both. observeErr records Go's actual err.Error(), so no
	// literal is restated.
	g.Canonical.UnterminatedError = observeErr(codec, "---\nname: unterminated fence, never closed\n")
	g.Canonical.NonmappingError = observeErr(codec, "---\n- top-level node is a sequence, not a mapping\n---\n")
	if wrapped := observeErr(codec, "---\ntitle: unquoted: colon\n---\n"); wrapped != "" {
		if i := strings.Index(wrapped, ": "); i >= 0 {
			g.Canonical.WrappedPrefix = wrapped[:i+2]
		}
	}

	for _, fc := range c.Frontmatter {
		// Observe what the real codec does; record its actual error text.
		msg := ""
		if _, err := codec.ParseConcept("conformance.md", []byte(fc.Input)); err != nil {
			msg = err.Error()
		}
		g.Frontmatter = append(g.Frontmatter, frontmatterResult{
			Name:       fc.Name,
			Error:      msg,
			PrefixOnly: fc.PrefixOnly,
		})
	}

	for _, a := range c.Actors {
		// Observe the real predicates; record what they actually return.
		g.Actors = append(g.Actors, actorResult{
			Actor:   a,
			IsHuman: okfrules.IsHumanActor(a),
			IsValid: okf.IsValidActor(a),
		})
	}

	for _, tc := range c.Tiers {
		fm := &okf.OrderedMap{}
		if len(tc.Verified) > 0 {
			list := make([]any, 0, len(tc.Verified))
			for _, v := range tc.Verified {
				m := map[string]any{"by": v.By}
				if v.At != "" {
					m["at"] = v.At
				}
				list = append(list, m)
			}
			fm.Set("verified", list)
		}
		con := &okf.Concept{Frontmatter: fm, Trust: okfrules.ProjectTrust(fm, "")}
		g.Tiers = append(g.Tiers, tierResult{
			Name: tc.Name,
			Tier: string(okfrules.TrustTier(con)),
		})
	}

	for _, sc := range c.Staleness {
		fm := &okf.OrderedMap{}
		if sc.StaleAfter != "" {
			fm.Set("stale_after", sc.StaleAfter)
		}
		con := &okf.Concept{Frontmatter: fm, Trust: okfrules.ProjectTrust(fm, "")}
		g.Staleness = append(g.Staleness, stalenessResult{
			Name:    sc.Name,
			IsStale: okfrules.IsStale(con, sc.Today),
		})
	}

	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	if err := enc.Encode(g); err != nil {
		fmt.Fprintf(os.Stderr, "gogolden: encoding golden: %v\n", err)
		os.Exit(2)
	}
}
